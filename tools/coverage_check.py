# the same item under a different name in the KG (P&ID tag used instead of the REPORT tag)
ALIASES = {"TT105": "TE105"}


def kg_name(tag):
    return ALIASES.get(tag, tag.replace("SOV", "SDV"))


g = Graph().parse(ROOT / "ccpp" / "full_plant.ttl")
kg_tags = {str(t) for t in g.objects(None, CCPP.tag)}
missing = {t: grid for t, grid in REPORT_TAGS.items() if kg_name(t) not in kg_tags}
covered = len(REPORT_TAGS) - len(missing)
print(f"Report tags covered: {covered} of {len(REPORT_TAGS)} ({100 * covered / len(REPORT_TAGS):.0f}%)")

areas = defaultdict(list)
for t, grid in sorted(missing.items()):
    col = int(re.sub(r"\D", "", grid)) if grid != "-" else 0
    area = ("columns 1-6" if 0 < col <= 6 else "columns 7-12" if col <= 12 and col else
            "columns 13-17" if 13 <= col <= 17 else "columns 18-23" if col >= 18 else "no grid")
    areas[area].append(f"{t} ({grid})")
for area in ["columns 1-6", "columns 7-12", "columns 13-17", "columns 18-23", "no grid"]:
    if areas[area]:
        print(f"\n{area}: {len(areas[area])} missing")
        print("  " + ", ".join(areas[area]))
